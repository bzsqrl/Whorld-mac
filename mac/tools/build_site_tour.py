# Builds the website's copy of A First Tour of Whorld, site/tour.html, from
# the app's Help page, mac/app/Help/tour.html, so the two say the same: the
# Help page's body in the site's look, with a bar back to the home page, its
# pictures from site/img/tour (copied from mac/app/Help/tour), and its links
# to the app's other Help pages pointing at the app instead. Run it after
# changing the Help page:
#   python3 mac/tools/build_site_tour.py

import html
import pathlib
import re
import shutil

repo = pathlib.Path(__file__).resolve().parents[2]
help_page = repo / "mac/app/Help/tour.html"
help_img = repo / "mac/app/Help/tour"
site = repo / "site"
out = site / "tour.html"

src = help_page.read_text(encoding="utf-8")
body = re.search(r"<body>\n(.*)</body>", src, re.S).group(1)
title = html.unescape(re.search(r"<title>(.*?)</title>", src).group(1))

# the pictures beside the page
body = body.replace('src="tour/', 'src="img/tour/')
body = body.replace("<img ", '<img loading="lazy" ')

# the app's other Help pages aren't on the site: name them in the app
ending = re.search(r'<p>The rest is in <a href="index.html">.*?</p>', body, re.S)
assert ending, "the Help page's last paragraph changed: update build_site_tour.py"
body = body.replace(ending.group(0),
	"<p>The rest is in the app: <b>Help &gt; Whorld Help</b> covers everything, "
	"<b>Help &gt; Tips and Gestures</b> has the shortcuts and gestures that are easy to miss, "
	"and <b>Help &gt; Whorld Manual</b> (the original Whorld manual) explains each parameter in depth.</p>")
assert 'href="index.html"' not in body and 'href="tips.html"' not in body and 'href="frames.html"' not in body

# who it's for, on the web: where to get the app
body = body.replace('Allow half an hour, and keep Whorld open beside this page.</p>',
	'Allow half an hour, and keep Whorld open beside this page. '
	'<a href="index.html#install">Download Whorld</a> first if you haven\'t; '
	'the same tour is in the app, under Help &gt; A First Tour of Whorld.</p>', 1)
assert "Download Whorld" in body, "the Help page's introduction changed: update build_site_tour.py"

